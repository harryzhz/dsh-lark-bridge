#!/usr/bin/env node
/**
 * Regenerate src/assets/lark-emoji.ts from the official Lark reaction catalog.
 *
 * Usage: node scripts/generate-emoji-assets.mjs
 */
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const DOC_URL =
  'https://open.feishu.cn/document_portal/v1/document/get_detail?fullPath=/uAjLw4CM/ukTMukTMukTM/reference/im-v1/message-reaction/emojis-introduce'

const SELECTED = [
  ['OnIt', '处理中'],
  ['OneSecond', '稍等'],
  ['Typing', '敲键盘'],
  ['Get', 'Get'],
  ['OK', 'OK'],
  ['DONE', '完成'],
  ['LGTM', 'LGTM'],
  ['THUMBSUP', '赞'],
  ['SALUTE', '敬礼'],
  ['MUSCLE', '加油'],
  ['THINKING', '思考'],
  ['GLANCE', '瞄'],
  ['CheckMark', '对勾'],
  ['FISTBUMP', '碰拳'],
]

const pkgRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outFile = resolve(pkgRoot, 'src/assets/lark-emoji.ts')

const doc = await (await fetch(DOC_URL)).json()
const content = String(doc?.data?.content ?? '')
const pattern =
  /<md-td>!\[[^\]]*\]\(((?:https:)?\/\/[^)?\s]+)[^)]*\)<\/md-td>\s*<md-td>([^<]+)<\/md-td>/g
const catalog = new Map()
for (const match of content.matchAll(pattern)) {
  const url = match[1].startsWith('//') ? `https:${match[1]}` : match[1]
  catalog.set(match[2].trim(), url)
}

const workDir = mkdtempSync(join(tmpdir(), 'lark-emoji-'))
const entries = []
for (const [type, label] of SELECTED) {
  const url = catalog.get(type)
  if (!url) throw new Error(`emoji_type "${type}" not found in reaction catalog`)
  const raw = join(workDir, `${type}.png`)
  const small = join(workDir, `${type}.48.png`)
  writeFileSync(raw, Buffer.from(await (await fetch(url)).arrayBuffer()))
  execFileSync('sips', ['-Z', '48', raw, '--out', small], { stdio: 'ignore' })
  const dataUri = `data:image/png;base64,${readFileSync(small).toString('base64')}`
  entries.push(`  { type: '${type}', label: '${label}', src: '${dataUri}' },`)
}

writeFileSync(
  outFile,
  `// Generated by scripts/generate-emoji-assets.mjs — do not edit by hand.
// Artwork © Lark / Open Platform reaction catalog.

export interface LarkEmojiAsset {
  /** Reaction \`emoji_type\` accepted by the message reaction API. */
  readonly type: string
  /** Display name shown in the reaction picker. */
  readonly label: string
  /** Inline 48px PNG artwork. */
  readonly src: string
}

export const LARK_EMOJI_ASSETS: readonly LarkEmojiAsset[] = [
${entries.join('\n')}
]
`,
  'utf8',
)
console.log(`Wrote ${entries.length} Lark emoji assets to ${outFile}`)
